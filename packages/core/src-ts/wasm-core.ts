/**
 * The Wasm-backed `PixelKernels` (design.md D5/D7). Wraps the wasm-bindgen
 * glue `wasm-pack build --target web` generates into `../pkg/` — `index.ts`
 * is the only other file that imports this one; nothing outside this package
 * touches `../pkg/` directly.
 *
 * Memory contract (design D7, confirmed in the wasm-bindgen docs): a
 * `&[u8]`/`&mut [u8]` argument is COPIED into Wasm memory and (for `&mut`)
 * copied back out once the call returns — there is no shared-memory aliasing
 * with JS across a call. A `Vec<u8>`/`Box<[u32]>` return is always a fresh
 * copy too. So every kernel call here pays one (or two, for a `&mut` arg)
 * copies — fine for whole-buffer kernels at the sizes this editor works with
 * (a 256x256 layer is 256KB), see `bench/` for the measured cost.
 */
import { CHANNELS, inBounds, isValidU32, validBuffer } from './ts-core'
import type { PixelKernels } from './types'

// wasm-pack's `--target web` output — generated by `pnpm run build:wasm`
// (NOT committed source, but the compiled `pkg/` output IS committed per
// design D9; see this package's README/build script for why).
// eslint-disable-next-line @typescript-eslint/no-explicit-any
type WasmExports = typeof import('../pkg/pixelforge_core')

let wasmModule: WasmExports | null = null

/**
 * Loads the Wasm module exactly once, via the exact same `import('../pkg/
 * pixelforge_core.js')` the browser uses. Throws if `pkg/` hasn't been built
 * (`pnpm run build:wasm`) — callers (always `resolveKernels`) must catch
 * this and fall back to `tsKernels`.
 *
 * W6 (phase 4f): `initWasm` is the ONE injectable seam — it decides how the
 * already-imported glue module turns into a running instance. Production
 * (the default, i.e. every real call site in this codebase) calls
 * `mod.default()`, which is the glue's own `fetch(new URL('pixelforge_core_bg
 * .wasm', import.meta.url))` — this is "the production wasm loader" the
 * test suite exercises, not a parallel/simplified test-only path. A test
 * running under Node (no working relative-URL `fetch` for a local file in
 * every environment) passes `(mod) => mod.initSync({ module: readFileSync(..
 * .) })` instead — same `loadWasmModule` function, same dynamic import of
 * the real generated glue, only the init STRATEGY differs.
 */
export async function loadWasmModule(
  initWasm: (mod: WasmExports) => unknown | Promise<unknown> = (mod) => mod.default()
): Promise<WasmExports> {
  if (!wasmModule) {
    const mod = await import('../pkg/pixelforge_core.js')
    await initWasm(mod)
    wasmModule = mod
  }
  return wasmModule
}

/** Test-only: forgets the cached module so a later `loadWasmModule` call re-imports/re-initializes from scratch (otherwise every test after the first would just get back the FIRST test's cached instance, regardless of what `initWasm` it passed). */
export function resetWasmModuleForTests(): void {
  wasmModule = null
}

/**
 * `true` iff `error` is a Wasm trap crossing back into JS as a catchable
 * `WebAssembly.RuntimeError` (confirmed empirically during judgment-day: a
 * Rust panic at the FFI boundary does NOT abort the whole Wasm instance the
 * way an unhandled JS exception would — it surfaces as this specific error
 * type, and the SAME instance can still be called again afterward). This
 * crate's boundary (`bindings.rs`) is designed to never panic on any input
 * this facade sends it (W2/W3 hardening) — reaching this path at all would
 * mean either a bug slipped past that hardening, or memory the Wasm
 * instance allocated earlier got corrupted by something else. Either way,
 * the safe response is the same: stop trusting this Wasm instance.
 */
function isWasmRuntimeError(error: unknown): boolean {
  return typeof WebAssembly !== 'undefined' && error instanceof WebAssembly.RuntimeError
}

/** Builds the `PixelKernels` facade over an already-initialized Wasm module (used by both the browser path and tests — see `pixel-parity.test.ts`, which initializes the module itself via `initSync`+`readFileSync` per design.md's "Testing Strategy", then calls this). */
export function makeWasmKernels(mod: WasmExports): PixelKernels {
  return {
    impl: 'wasm',
    // T1 (phase 4f): `get_pixel`/`put_pixel` stay exported from the Rust
    // `bindings.rs` (useful Rust-side building blocks), but this facade no
    // longer wraps them — `putPoints` is the one pixel-writing entry point.
    //
    // Phase 5f.5: `w`/`h` are validated with the SAME `isValidU32`/
    // `validBuffer` guard `tsKernels` uses, BEFORE calling into Wasm — a
    // wasm-bindgen `u32` parameter silently truncates/wraps a NaN,
    // fractional, negative, or out-of-range (e.g. `2**32 + 1`) JS number via
    // the JS-API's `ToUint32` coercion instead of rejecting it, which would
    // make the Rust side receive a DIFFERENT, "valid-looking" value than
    // what was actually passed — this guard makes sure that coercion is
    // simply never reached for an invalid number; both kernels reject
    // identically instead.
    putPoints: (data, w, h, points, rgba) => (!isValidU32(w) || !isValidU32(h) || !validBuffer(data, w, h) ? 0 : mod.put_points(data, w, h, points, rgba)),
    // Phase 5: `mod.flood_fill` returns the Rust side's packed `[x,y,w,h]`
    // (a `Box<[u32]>`, wasm-bindgen's `Uint32Array`-like return) or `undefined`
    // for "nothing changed" — unpacked into the same plain tuple shape
    // `tsKernels.floodFill` returns, so callers never see a Rust/Wasm-specific
    // return type.
    floodFill: (data, w, h, x, y, rgba) => {
      if (!isValidU32(w) || !isValidU32(h) || !validBuffer(data, w, h) || !inBounds(w, h, x, y)) return undefined
      const packed = mod.flood_fill(data, w, h, x, y, rgba)
      return packed ? [packed[0], packed[1], packed[2], packed[3]] : undefined
    },
    cloneBuffer: (data) => mod.clone_buffer(data),
    diffRect: (before, after, w, h) => {
      if (!isValidU32(w) || !isValidU32(h) || !validBuffer(before, w, h) || !validBuffer(after, w, h)) return undefined
      const packed = mod.diff_rect(before, after, w, h)
      return packed ? [packed[0], packed[1], packed[2], packed[3]] : undefined
    },
    extractRect: (data, w, h, rx, ry, rw, rh) => {
      if (
        !isValidU32(w) ||
        !isValidU32(h) ||
        !validBuffer(data, w, h) ||
        !isValidU32(rx) ||
        !isValidU32(ry) ||
        !isValidU32(rw) ||
        !isValidU32(rh) ||
        rw === 0 ||
        rh === 0 ||
        rx + rw > w ||
        ry + rh > h
      )
        return undefined
      return mod.extract_rect(data, w, h, rx, ry, rw, rh) ?? undefined
    },
    writeRect: (data, w, h, rx, ry, rw, rh, patch) => {
      if (
        !isValidU32(w) ||
        !isValidU32(h) ||
        !validBuffer(data, w, h) ||
        !isValidU32(rx) ||
        !isValidU32(ry) ||
        !isValidU32(rw) ||
        !isValidU32(rh) ||
        rw === 0 ||
        rh === 0 ||
        rx + rw > w ||
        ry + rh > h ||
        patch.length !== rw * rh * CHANNELS
      )
        return false
      return mod.write_rect(data, w, h, rx, ry, rw, rh, patch)
    },
    bytesEqual: (a, b) => mod.bytes_equal(a, b),
    // Phase 6: same `isValidU32` boundary guard as every other numeric
    // kernel argument (see `ts-core.ts`'s `quantize`/`isValidU32` docs) —
    // applied BEFORE calling into Wasm, so a wasm-bindgen `u32` param never
    // silently coerces a NaN/fractional/out-of-range `colors`/`iterations`/
    // `alphaThreshold` into a "valid-looking" different number.
    quantize: (data, colors, weightBySaturation, iterations, alphaThreshold) => {
      if (data.length % CHANNELS !== 0 || !isValidU32(colors) || !isValidU32(iterations) || !isValidU32(alphaThreshold)) return undefined
      return mod.quantize(data, colors, weightBySaturation, iterations, alphaThreshold) ?? undefined
    },
    downscale: (data, srcW, srcH, targetW, targetH) => {
      if (!isValidU32(srcW) || !isValidU32(srcH) || !isValidU32(targetW) || !isValidU32(targetH) || !validBuffer(data, srcW, srcH)) return undefined
      return mod.downscale(data, srcW, srcH, targetW, targetH) ?? undefined
    },
  }
}
